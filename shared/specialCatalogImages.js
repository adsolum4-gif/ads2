export function specialProductLabelFromName(name) {
  if (!name || typeof name !== "string") return null;
  const parts = name.split(" — ");
  if (parts.length >= 2) return parts.slice(1).join(" — ").trim();
  return null;
}

export function specialCatalogImageForName(name) {
  const label = specialProductLabelFromName(name);
  if (!label) return null;
  return SPECIAL_CATALOG_IMAGES[label] || null;
}
